// Backing recorded for `name`, or Unimplemented when the name is unknown --
// an unknown tool is by definition backed by nothing, so the safe answer and
// the truthful one coincide.
[[nodiscard]] Backing ToolBackingFor(std::string_view name);

// Whether `name` appears in the table at all. Distinguishes "recorded as
// unbacked" from "never recorded", which ToolBackingFor() deliberately
// collapses.
[[nodiscard]] bool ToolBackingKnown(std::string_view name);

// Human-readable label used in tool descriptions and error messages.
[[nodiscard]] std::string_view BackingName(Backing backing);

// Verifies the table is sorted, free of duplicates, and in sync with the
// registered handlers. Called once at startup; asserts in debug builds and
// logs in release so a drifted table is visible either way.
void VerifyToolBackings(const QStringList &registeredToolNames);

