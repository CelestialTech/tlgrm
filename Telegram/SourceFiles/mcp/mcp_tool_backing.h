// What actually answers a tool call.
//
// A tool used to be declared in three hand-synced places -- a header
// signature, a schema entry in registerTools(), and a lambda in the
// _toolHandlers map -- with nothing linking them. That let one tool get
// advertised twice, five get their handler assigned twice, and eight become
// callable while never being advertised at all. Worse, nothing recorded
// whether a tool had any data source, so tools that invented their answer
// reported success indistinguishably from tools that queried Telegram.
//
// This table is the single place that records what backs each tool. The
// server consults it on every call, so a tool nothing backs cannot report
// success no matter what its implementation does.
enum class Backing {
	// Issues Telegram API requests. The answer comes from Telegram.
	Mtproto,

	// Reads live session state already synced from Telegram.
	LiveSession,

	// Derives its answer from its arguments alone -- no I/O, no state.
	// Honest and deterministic; simply not a Telegram query.
	PureCompute,

	// Reads or writes only this client's local database. Nothing syncs that
	// database from Telegram, so results describe local state and must not
	// be read as Telegram's view of the world.
	LocalOnly,

	// Nothing backs this tool. It must never report success: returning
	// success here is what made 20 tools indistinguishable from working
	// ones. Callers get an explicit error instead.
	Unimplemented,
};

struct ToolBackingEntry {
	std::string_view name;
	Backing backing;
};

